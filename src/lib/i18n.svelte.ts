class I18nStore {
  locale = $state<Locale>('en');

  constructor() {
    if (typeof localStorage !== 'undefined') {
      const saved = localStorage.getItem('finnca_locale') as Locale | null;
      if (saved === 'en' || saved === 'id') {
        this.locale = saved;
      }
    }
  }

  setLocale(l: Locale) {
    this.locale = l;
    if (typeof localStorage !== 'undefined') {
      localStorage.setItem('finnca_locale', l);
    }
  }

  get t() {
    return dict[this.locale];
  }
}

export const i18n = new I18nStore();
